async function fetchJson(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`PokéAPI ${response.status}: ${url}`);
  return response.json();
}
async function mapLimit(items, limit, fn) {
  const results = new Array(items.length);
  let cursor = 0;
  await Promise.all(Array.from({ length: limit }, async () => {
    while (cursor < items.length) {
      const index = cursor++;
      results[index] = await fn(items[index]);
    }
  }));
  return results;
}
async function load(id) {
  const [pokemon, species] = await Promise.all([
    fetchJson(`https://pokeapi.co/api/v2/pokemon/${id}`),
    fetchJson(`https://pokeapi.co/api/v2/pokemon-species/${id}`)
  ]);
  return {
    id,
    name: pokemon.name,
    types: pokemon.types.slice().sort((a,b) => a.slot - b.slot).map(x => x.type.name),
    bst: pokemon.stats.reduce((sum, stat) => sum + stat.base_stat, 0),
    generation: Number(species.generation.url.match(/generation\/(\d+)/)[1]),
    sprite: `https://raw.githubusercontent.com/PokeAPI/sprites/master/sprites/pokemon/${id}.png`,
    legendary: species.is_legendary,
    mythical: species.is_mythical
  };
}
(async () => {
  if (draftIds.length !== 144 || new Set(draftIds).size !== 144) throw new Error('Draft must have exactly 144 unique IDs.');
  for (const [generation, ids] of Object.entries(DRAFT_IDS_BY_GENERATION)) {
    if (ids.length !== 16) throw new Error(`Generation ${generation} must have 16 IDs.`);
  }
  const rows = await mapLimit(allIds, 12, load);
  const lookup = new Map(rows.map(row => [row.id, row]));
  for (const [generation, ids] of Object.entries(DRAFT_IDS_BY_GENERATION)) {
    for (const id of ids) {
      const row = lookup.get(id);
      if (row.generation !== Number(generation) || row.legendary || row.mythical) {
        throw new Error(`Invalid draft species #${id}: generation=${row.generation}, legendary=${row.legendary}, mythical=${row.mythical}`);
      }
    }
  }
  const output = `/* Generated by scripts/build-campaign-draft-catalog.js. Do not fetch at runtime. */\n(function () {\n  const freeze = entry => Object.freeze({ ...entry, types: Object.freeze(entry.types) });\n  const entries = Object.freeze(${JSON.stringify(rows.sort((a,b) => a.id - b.id), null, 2)}.map(freeze));\n  const byId = Object.freeze(Object.fromEntries(entries.map(entry => [entry.id, entry])));\n  const api = Object.freeze({ entries, byId });\n  if (typeof module !== 'undefined' && module.exports) module.exports = api;\n  else { window.PBACampaign = window.PBACampaign || {}; window.PBACampaign.CampaignPokemonCatalog = api; }\n})();\n`;
  fs.writeFileSync(path.join(__dirname, '..', 'assets', 'js', 'campaign', 'campaign-pokemon-catalog.js'), output);
  console.log(JSON.stringify({ generated: rows.length, draft: draftIds.length, generations: Object.keys(DRAFT_IDS_BY_GENERATION).length }, null, 2));
})().catch(error => { console.error(error); process.exitCode = 1; });